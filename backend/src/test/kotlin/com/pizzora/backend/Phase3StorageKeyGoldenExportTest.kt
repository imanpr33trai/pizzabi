package com.pizzora.backend

import com.pizzora.backend.core.security.StorageKeyValidator
import java.io.File
import kotlinx.serialization.Serializable
import kotlinx.serialization.encodeToString
import kotlinx.serialization.json.Json
import org.junit.Assert.assertTrue
import org.junit.Test

class Phase3StorageKeyGoldenExportTest {
  private val prettyJson = Json {
    prettyPrint = true
    encodeDefaults = true
  }

  @Serializable
  data class StorageKeyBundle(
    val source: String,
    val cases: List<StorageKeyCase>,
  )

  @Serializable
  data class StorageKeyCase(
    val raw_key: String,
    val expected_valid: Boolean,
  )

  private fun findRepoRoot(): File {
    var dir = File(System.getProperty("user.dir")).canonicalFile
    while (dir.parentFile != null) {
      if (File(dir, "tools").isDirectory && File(dir, "settings.gradle.kts").isFile) {
        return dir
      }
      dir = dir.parentFile
    }
    error("Could not locate repository root from ${System.getProperty("user.dir")}")
  }

  @Test
  fun `export and verify storage key golden vectors from Kotlin StorageKeyValidator`() {
    val candidateKeys = listOf(
      "products/123/hero-1.webp",
      "A",
      "catalog/2026/11/pizza_01.v2.jpg",
      "a".repeat(255),
      "a".repeat(256),
      "",
      "   ",
      " products/a.jpg",
      "products/a.jpg ",
      "/products/a.jpg",
      "products\\a.jpg",
      "products/\u0000a.jpg",
      "products//a.jpg",
      "products/../secret.jpg",
      "products/%2e%2e/secret.jpg",
      "products/%2E/secret.jpg",
      "products/%2f/secret.jpg",
      "products/%2Fsecret.jpg",
      "products/%5csecret.jpg",
      "products/%5Csecret.jpg",
      "-leading-dash.jpg",
      "_leading_underscore.jpg",
      ".leading-dot.jpg",
      "products/space in name.jpg",
    )

    val cases = candidateKeys.map { raw ->
      val valid = runCatching { StorageKeyValidator.validateObjectKey(raw) }.isSuccess
      StorageKeyCase(raw_key = raw, expected_valid = valid)
    }

    val outFile = File(findRepoRoot(), "tools/golden-vectors/storage_key_parity.json")
    outFile.parentFile.mkdirs()
    outFile.writeText(
      prettyJson.encodeToString(
        StorageKeyBundle(
          source = "Generated by Kotlin :backend Phase3StorageKeyGoldenExportTest",
          cases = cases,
        ),
      ) + "\n",
    )
    assertTrue(outFile.exists())
  }
}
